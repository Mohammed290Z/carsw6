type I18n = {
  lang: Lang; rtl: boolean; locale: string;
  t: (key: string, p?: any) => string;
  setLang: (l: Lang) => void;
  fmt: (n: number) => string;
  money: (n: number) => string;
};
const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  const saved = store.get('lang');
  if (saved === 'fr' || saved === 'en' || saved === 'ar') return saved;
  const code = Localization.getLocales()[0]?.languageCode;
  return code === 'ar' ? 'ar' : code === 'en' ? 'en' : 'fr';
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, set] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => { store.set('lang', l); set(l); }, []);
  const value = useMemo<I18n>(() => {
    const locale = LANGS.find(l => l.id === lang)!.locale;
    const nf = new Intl.NumberFormat(locale);
    const t = (key: string, p?: any) => { const v = S[lang][key] ?? S.fr[key] ?? key; return typeof v === 'function' ? v(p) : v; };
    return { lang, rtl: lang === 'ar', locale, t, setLang, fmt: n => nf.format(n), money: n => `${nf.format(n)} ${t('currency')}` };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => { const v = useContext(Ctx); if (!v) throw new Error('I18nProvider missing'); return v; };
